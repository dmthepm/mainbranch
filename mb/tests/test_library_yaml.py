"""Library YAML inputs: no aliases or merges, bounded reads, bounded writes, exact types.

Everything here is invented: made-up names, generated bytes, tmp dirs. The
memory-hungry probes run in a child process with a hard address-space cap, so a
regression fails that child and never the host.
"""

from __future__ import annotations

import resource
import subprocess
import sys
from collections.abc import Callable, Iterator
from datetime import datetime, timezone
from pathlib import Path

import pytest

from mb import library_files as files
from mb import library_store as store
from tests.library_fixtures import lock, make_tree, needs_nonroot, sha, unlock

NOW = datetime(2026, 11, 5, 12, 0, tzinfo=timezone.utc)
CAP = 128 * 1024 * 1024
PACKAGE_ROOT = str(Path(store.__file__).resolve().parents[1])


def run_capped(code: str, *args: str) -> str:
    """Run `code` in a child python limited to 128 MiB; return its stdout, stripped."""

    def limit() -> None:
        resource.setrlimit(resource.RLIMIT_AS, (CAP, CAP))

    done = subprocess.run(
        [sys.executable, "-I", "-c", code, *args],
        capture_output=True,
        text=True,
        timeout=60,
        preexec_fn=limit,
        check=False,
    )
    return done.stdout.strip() or f"no output; stderr: {done.stderr[-400:]}"


_TRY = (
    "import sys\n"
    f"sys.path.insert(0, {PACKAGE_ROOT!r})\n"
    "from pathlib import Path\n"
    "from mb import library_store as s\n"
    "from mb.library_files import LibraryError\n"
)


@pytest.fixture()
def biz(tmp_path: Path) -> Path:
    root = tmp_path / "acme-candles"
    (root / ".mb").mkdir(parents=True)
    return root


@pytest.fixture()
def tree(tmp_path: Path) -> Iterator[Callable[[dict[str, bytes]], Path]]:
    made: list[Path] = []

    def factory(contents: dict[str, bytes]) -> Path:
        root = make_tree(tmp_path / "sources" / f"studio{len(made)}", contents)
        made.append(root)
        return lock(root)

    yield factory
    for root in made:
        unlock(root)


def library(biz: Path, *, init: bool = False) -> store.Library:
    return store.Library(biz, now=lambda: NOW, init=init)


# --- B: aliases and merges are refused before anything is built --------------


def merge_bomb() -> str:
    lines = ["a0: &a0 {key: value}"]
    for i in range(1, 24):
        lines.append(f"a{i}: &a{i} {{<<: [*a{i - 1}, *a{i - 1}]}}")
    return "\n".join(lines)


def test_a_merge_alias_bomb_is_a_named_refusal_not_a_memory_error(tmp_path: Path) -> None:
    code = _TRY + (
        "raw = Path(sys.argv[1]).read_bytes()\n"
        "try:\n"
        "    s._load_yaml(raw, 'probe.yaml')\n"
        "except LibraryError as e:\n"
        "    print('LibraryError', e)\n"
        "except BaseException as e:\n"
        "    print(type(e).__name__)\n"
    )
    path = tmp_path / "bomb.yaml"
    path.write_text(merge_bomb())
    out = run_capped(code, str(path))
    assert out.startswith("LibraryError"), out
    assert "alias" in out or "merge" in out


@pytest.mark.parametrize(
    "text",
    [
        "a: &x 1\nb: *x\n",
        "base: &b {k: v}\nother:\n  <<: *b\n",
        "other:\n  <<: {k: v}\n",
        "other:\n  <<: [{k: v}]\n",
    ],
)
def test_aliases_and_merge_keys_are_refused_by_name(text: str) -> None:
    with pytest.raises(files.LibraryError, match="alias|merge"):
        store._load_yaml(text.encode(), "probe.yaml")


def test_a_quoted_merge_looking_key_is_ordinary_text() -> None:
    assert store._load_yaml(b"'<<': v\n", "probe.yaml") == {"<<": "v"}


@needs_nonroot
def test_a_record_with_an_alias_is_refused_by_the_library(
    biz: Path, tree: Callable[[dict[str, bytes]], Path]
) -> None:
    lib = library(biz, init=True)
    lib.add_source("studio", tree({"clip.jpg": b"clip bytes"}))
    lib.scan()
    asset = sha(b"clip bytes")
    record = biz / "library" / "records" / f"{asset}.yaml"
    record.parent.mkdir(parents=True, exist_ok=True)
    record.write_text(f"asset: {asset}\ntags: &t [a]\ncreator: x\nextra: *t\n")
    record.chmod(0o600)
    with pytest.raises(files.LibraryError, match="alias|merge"):
        lib.show(asset)


@needs_nonroot
@pytest.mark.parametrize("which", ["config", "record"])
def test_an_oversized_yaml_file_is_refused_without_being_read_whole(
    which: str, biz: Path, tree: Callable[[dict[str, bytes]], Path]
) -> None:
    lib = library(biz, init=True)
    lib.add_source("studio", tree({"clip.jpg": b"clip bytes"}))
    lib.scan()
    asset = sha(b"clip bytes")
    if which == "config":
        big = biz / ".mb/private/library/config.yaml"
    else:
        big = biz / "library" / "records" / f"{asset}.yaml"
        big.parent.mkdir(parents=True, exist_ok=True)
    with big.open("wb") as handle:
        handle.truncate(96 * 1024 * 1024)
    big.chmod(0o600)
    code = _TRY + (
        "try:\n"
        "    lib = s.Library(Path(sys.argv[1]))\n"
        "    if sys.argv[2] == 'record':\n"
        "        lib.show(sys.argv[3])\n"
        "except LibraryError as e:\n"
        "    print('LibraryError', e)\n"
        "except BaseException as e:\n"
        "    print(type(e).__name__)\n"
    )
    out = run_capped(code, str(biz), which, asset)
    assert out.startswith("LibraryError"), out
    assert "too large" in out
