@needs_nonroot
def test_verify_names_a_file_whose_bytes_changed_under_the_same_size_and_mtime(studio):
    biz, src, lib = studio
    lib.scan()
    path = src / "candle-pour-01.jpg"
    stat_before = path.stat()
    src.chmod(0o755)
    path.chmod(0o644)
    altered = bytes(reversed(POUR))
    assert len(altered) == len(POUR) and altered != POUR
    path.write_bytes(altered)
    os.utime(path, ns=(stat_before.st_atime_ns, stat_before.st_mtime_ns))
    path.chmod(0o444)
    src.chmod(0o555)
    assert lib.scan().changed == 0  # the fast path trusts size and mtime
    report = lib.scan(verify=True)
    assert report.mismatched == ["studio:candle-pour-01.jpg"]
    assert lib.show(sha(altered)).sightings == ["studio:candle-pour-01.jpg"]


