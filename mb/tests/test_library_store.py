    assert [(h.asset, h.cleared) for h in hits] == [(POUR_ID, [sighting])]
    assert lib.find("pour", use=rights.Use("paid-ad", "tiktok"), window=WINDOW) == []

    shown = lib.show(POUR_ID).deals[0]
