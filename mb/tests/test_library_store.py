@needs_nonroot
def test_killed_scan_then_rerun_gives_the_same_index_as_an_uninterrupted_one(biz, tmp_path):
    names = {f"p{i}.jpg": blob(f"p{i}") for i in range(7)}
    src = make_tree(tmp_path / "sources" / "studio", names)
    lock(src)
    try:
        interrupted = tmp_path / "interrupted"
        (interrupted / ".mb").mkdir(parents=True)
        library(interrupted, init=True).add_source("studio", src)
        script = textwrap.dedent(
            f"""
            import os, signal, sys
            from pathlib import Path
            sys.path.insert(0, {str(Path(store.__file__).parent.parent)!r})
            from mb import library_source, library_store
            library_store.BATCH = 2
            real, calls = library_source._hash, [0]
            def killer(*args):
                calls[0] += 1
                if calls[0] == 5:
                    os.kill(os.getpid(), signal.SIGKILL)
                return real(*args)
            library_source._hash = killer
            library_store.Library(Path({str(interrupted)!r})).scan()
            """
        )
        done = subprocess.run([sys.executable, "-I", "-c", script], check=False)
        assert done.returncode == -signal.SIGKILL
        partial = library(interrupted).find("")
        assert 0 < len(partial) < 7  # the kill really did land mid-scan
        library(interrupted).scan()

        clean = tmp_path / "clean"
        (clean / ".mb").mkdir(parents=True)
        fresh = library(clean, init=True)
        fresh.add_source("studio", src)
        fresh.scan()
        assert [(h.asset, h.sightings) for h in library(interrupted).find("")] == [
            (h.asset, h.sightings) for h in fresh.find("")
        ]
        assert len(fresh.find("")) == 7
    finally:
        unlock(src)


