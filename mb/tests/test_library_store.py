@needs_nonroot
def test_today_follows_the_business_timezone(biz, read_only_source):
    late = datetime(2026, 12, 31, 23, 30, tzinfo=timezone.utc)
    src = read_only_source({"candle-pour-01.jpg": POUR})
    lib = library(biz, init=True, now=late)
    lib.add_source("studio", src)
    lib.scan()
    deal = propose(lib, POUR_ID, to_date=date(2026, 12, 31))
    own(biz, POUR_ID)
    lib.approve_deal(deal.id, deal.id, has_terminal=True, approver="Rowan Vale")
    use = rights.Use("paid-ad", "meta")

    def on_the_last_day(now: datetime) -> list[bool]:
        return [s.verdict.cleared for s in library(biz, now=now).check(POUR_ID, use, window=None)]

    # `propose` ran with from 2026-12-01; the default window is "today".
    assert on_the_last_day(late) == [True]  # UTC: still 31 Dec
    cfg = biz / ".mb/private/library/config.yaml"
    data = yaml.safe_load(cfg.read_text())
    data["timezone"] = "Pacific/Auckland"
    cfg.write_text(yaml.safe_dump(data))
    assert on_the_last_day(late) == [False]  # Auckland: already 1 Jan


@needs_nonroot
def test_deal_ids_are_short_and_unique(studio):
    _, _, lib = studio
    lib.scan()
    ids = {propose(lib, POUR_ID).id for _ in range(5)}
    assert len(ids) == 5
    assert all(len(i) == 8 and int(i, 16) >= 0 for i in ids)
