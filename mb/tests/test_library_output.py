@needs_nonroot
@pytest.mark.parametrize("key", DEAL_KEYS)
def test_no_deal_field_can_put_a_raw_control_in_any_output(
    key: str,
    biz: Path,
    tree: Callable[[dict[str, bytes]], Path],
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    world = World(biz, tree({"clip.jpg": b"clip bytes", f"a{CONTROLS}b.jpg": b"odd name"}))
    world.edit_record(lambda d: d["deals"][0].update({key: hostile_like(d["deals"][0][key])}))
    monkeypatch.chdir(biz)
    for verb, output, _ in every_verb(world, "e" * 64, tree({"other.jpg": b"o"})):
        assert_plain(output, (key, verb))


