@needs_nonroot
@pytest.mark.parametrize("key", ["timezone", "records_dir", "sources"])
@pytest.mark.parametrize("shape", ["value", "name"])
def test_no_config_field_can_put_a_raw_control_in_any_output(
    key: str,
    shape: str,
    biz: Path,
    tree: Callable[[dict[str, bytes]], Path],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    world = World(biz, tree({"clip.jpg": b"clip bytes"}))
    if key == "sources":
        if shape == "name":
            world.edit_config(lambda d: d.update(sources={HOST: str(world.src)}))
        else:
            world.edit_config(lambda d: d.update(sources={"studio": HOST}))
    elif shape == "value":
        world.edit_config(lambda d: d.update({key: HOST}))
    else:
        return
    monkeypatch.chdir(biz)
    for verb, output, _ in every_verb(world, "e" * 64, tree({"other.jpg": b"o"})):
        assert_plain(output, (key, shape, verb))


@needs_nonroot
def test_an_unavailable_source_label_is_escaped(
    biz: Path, tree: Callable[[dict[str, bytes]], Path], monkeypatch: pytest.MonkeyPatch
) -> None:
    world = World(biz, tree({"clip.jpg": b"clip bytes"}))
    unlock(world.src)
    world.src.rename(world.src.with_name("moved"))
    monkeypatch.chdir(biz)
    out = runner.invoke(app, ["library", "scan"], color=True)
    assert "Unavailable: studio" in out.output
    assert_plain(out.output, "unavailable")


