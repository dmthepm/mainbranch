@pytest.mark.parametrize("name", ["new\n", "a\n", "x\r", "bad name", "UP", ""])
@needs_nonroot
def test_a_source_name_must_match_whole_not_up_to_a_final_newline(
    name: str, biz: Path, tree: Callable[[dict[str, bytes]], Path]
) -> None:
    lib = store.Library(biz, now=lambda: NOW, init=True)
    with pytest.raises(files.LibraryError, match="source name"):
        lib.add_source(name, tree({"clip.jpg": b"x"}))


@pytest.mark.parametrize(
    "row",
    [
        ["studio", "a.jpg", "z" * 64, 1, 1, "photo"],
        ["studio", "a.jpg", "a" * 64 + "\n", 1, 1, "photo"],
        ["studio", "a.jpg", "a" * 64, 1, 1, "photo\n"],
        ["studio", "a.jpg", "a" * 64, 1, 1, "hologram"],
        ["studio\n", "a.jpg", "a" * 64, 1, 1, "photo"],
    ],
)
def test_an_index_row_with_a_bad_asset_kind_or_source_is_refused(row: list[Any], biz: Path) -> None:
    store.Library(biz, init=True)
    folder = biz / ".mb/private/library"
    (folder / "index.json").write_text(json.dumps({"version": 1, "sightings": [row]}))
    (folder / "index.json").chmod(0o600)
    fd = files.open_dir(biz, ".mb/private/library", create=False)
    try:
        with pytest.raises(files.LibraryError, match="index"):
            Index.load(fd)
    finally:
        os.close(fd)


def _deal_mapping() -> dict[str, Any]:
    return rights.Deal(
        id="d7aa11bb",
        uses=("website",),
        platforms=(),
        from_date=date(2026, 1, 1),
        to_date=None,
        perpetual=True,
        music="none",
        platform_code=None,
        said_by="x",
        evidence_hash="",
        sightings=("studio:clip.jpg",),
    ).to_mapping()


@pytest.mark.parametrize("deal_id", ["x\nFORGED", "d7aa11bb\n", "D7AA11BB", "d7aa11", "", "d1"])
def test_a_deal_id_must_be_eight_lowercase_hex_characters(deal_id: str) -> None:
    raw = _deal_mapping()
    raw["id"] = deal_id
    with pytest.raises(ValueError, match="id"):
        rights.Deal.from_mapping(raw)


@pytest.mark.parametrize("field", ["approved_at", "revoked_at"])
@pytest.mark.parametrize("stamp", ["\nFAKE\x1b[2J", "yesterday", "2026-11-05T12:00:00+00:00\n"])
def test_a_deal_timestamp_must_be_empty_or_an_iso_time(field: str, stamp: str) -> None:
    raw = _deal_mapping()
    raw[field] = stamp
    with pytest.raises(ValueError, match=field):
        rights.Deal.from_mapping(raw)


def test_a_deal_with_real_timestamps_still_reads_back() -> None:
    raw = _deal_mapping()
    raw["approved_at"] = NOW.isoformat()
    raw["revoked_at"] = ""
    assert rights.Deal.from_mapping(raw).approved_at == NOW.isoformat()
