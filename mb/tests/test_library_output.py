def assert_plain(output: str, where: object) -> None:
    """No raw control byte except the line ends we print ourselves, and no forged line."""
    bad = [c for c in output if c != "\n" and unicodedata.category(c) in {"Cc", "Cf", "Zl", "Zp"}]
    assert not bad, (where, bad, output)
    assert not any(line.lstrip().startswith("FORGED") for line in output.splitlines()), where


@pytest.fixture()
def biz(tmp_path: Path) -> Path:
    root = tmp_path / "acme-candles"
    (root / ".mb").mkdir(parents=True)
    return root


@pytest.fixture()
def tree(tmp_path: Path) -> Iterator[Callable[[dict[str, bytes]], Path]]:
    made: list[Path] = []

    def factory(contents: dict[str, bytes]) -> Path:
        root = make_tree(tmp_path / "sources" / f"studio{len(made)}", contents)
        made.append(root)
        return lock(root)

    yield factory
    for root in made:
        unlock(root)


class World:
    """A business folder with one scanned asset, one approved deal and one proposed deal."""

    def __init__(self, biz: Path, src: Path) -> None:
        self.biz = biz
        self.src = src
        self.lib = store.Library(biz, now=lambda: NOW, init=True)
        self.lib.add_source("studio", src)
        self.lib.scan()
        self.asset = sha(b"clip bytes")
        self.record = biz / "library" / "records" / f"{self.asset}.yaml"
        terms: dict[str, Any] = {
            "uses": ("website",),
            "platforms": (),
            "from_date": date(2026, 1, 1),
            "to_date": date(2027, 1, 1),
            "perpetual": False,
            "music": "none",
            "said_by": "Rowan Vale",
        }
        first = self.lib.propose_deal(self.asset, **terms)
        self.lib.propose_deal(self.asset, **terms)
        self.edit_record(lambda d: d.update(provenance="own"))
        self.lib.approve_deal(first.id, first.id, has_terminal=True, approver="Rowan Vale")
        self.config = biz / ".mb/private/library/config.yaml"
        self.index = biz / ".mb/private/library/index.json"

    def edit_record(self, change: Callable[[dict[str, Any]], object]) -> None:
        data = yaml.safe_load(self.record.read_text())
        change(data)
        self.record.write_text(yaml.safe_dump(data, sort_keys=False))

    def edit_config(self, change: Callable[[dict[str, Any]], object]) -> None:
        data = yaml.safe_load(self.config.read_text())
        change(data)
        self.config.write_text(yaml.safe_dump(data, sort_keys=False))

    def edit_index(self, change: Callable[[dict[str, Any]], object]) -> None:
        data = json.loads(self.index.read_text())
        change(data)
        self.index.write_text(json.dumps(data))
        self.index.chmod(0o600)


def hostile_like(value: object) -> object:
    return [HOST] if isinstance(value, list) else HOST


def every_verb(world: World, extra_asset: str, source_dir: Path) -> list[tuple[str, str, int]]:
    """Run every library verb; return (verb, output, exit code) for each."""
    asset = world.asset
    deal_id = "00000000"
    commands = [  # scan comes last: it rewrites the index the earlier verbs must read as planted
        ["find"],
        ["find", "clip", "--kind", "photo"],
        ["find", "--for", "website"],
        ["show", asset],
        ["show", extra_asset],
        ["check", asset, "--use", "website", "--from", "2026-02-01", "--to", "2026-02-02"],
        ["check", extra_asset, "--use", "website"],
        ["source", "add", "fresh", str(source_dir)],
        ["deal", "approve", deal_id],
        ["deal", "approve", extra_asset],
        ["deal", "revoke", deal_id, "--reason", "r"],
        ["deal", "revoke", extra_asset, "--reason", HOST],
        [
            "deal",
            "propose",
            asset,
            "--use",
            "website",
            "--from",
            "2026-01-01",
            "--to",
            "2026-02-01",
            "--said-by",
            HOST,
            "--sighting",
            HOST,
        ],
        ["scan"],
        ["scan", "--verify"],
    ]
    results: list[tuple[str, str, int]] = []
    for args in commands:
        out = runner.invoke(app, ["library", *args], color=True)
        assert out.exception is None or isinstance(out.exception, SystemExit), (args, out.output)
        results.append((" ".join(args[:2]), out.output, out.exit_code))
    return results


