# --- finding 3: approval is bound to asset and provenance ------------------


@needs_nonroot
def test_a_record_copied_to_other_bytes_is_refused(
    biz: Path, tree: Callable[[dict[str, bytes]], Path]
) -> None:
    src = tree({"clip.jpg": b"first"})
    lib = library(biz, init=True)
    lib.add_source("studio", src)
    lib.scan()
    first = sha(b"first")
    deal = propose(lib, first)
    edit_record(biz, first, lambda d: d.update(provenance="own"))
    lib.approve_deal(deal.id, deal.id, has_terminal=True, approver="Rowan Vale")
    assert verdicts(lib, first)[0].cleared is True

    unlock(src)
    (src / "clip.jpg").write_bytes(b"second")
    os.utime(src / "clip.jpg", (OLD, OLD))
    lock(src)
    lib.scan()
    second = sha(b"second")
    (records_dir(biz) / f"{second}.yaml").write_bytes(
        (records_dir(biz) / f"{first}.yaml").read_bytes()
    )
    with pytest.raises(files.LibraryError, match="asset"):
        lib.check(second, USE, WINDOW)


@needs_nonroot
def test_changing_provenance_after_approval_needs_a_new_approval(
    biz: Path, tree: Callable[[dict[str, bytes]], Path]
) -> None:
    src = tree({"clip.jpg": b"first"})
    lib = library(biz, init=True)
    lib.add_source("studio", src)
    lib.scan()
    asset = sha(b"first")
    deal = propose(lib, asset, music="original")
    edit_record(biz, asset, lambda d: d.update(provenance="licensed"))
    lib.approve_deal(deal.id, deal.id, has_terminal=True, approver="Rowan Vale")
    assert verdicts(lib, asset)[0].reasons == ("platform-code-missing",)

