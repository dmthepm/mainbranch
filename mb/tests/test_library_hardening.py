@needs_nonroot
def test_a_second_scan_while_one_runs_is_refused_by_name(
    biz: Path, tree: Callable[[dict[str, bytes]], Path], monkeypatch: pytest.MonkeyPatch
) -> None:
    src = tree({"clip.jpg": b"first"})
    lib = library(biz, init=True)
    lib.add_source("studio", src)
    real = source.scan_source
    refusals: list[str] = []

    def scan_inside(*args: Any, **kwargs: Any) -> Iterator[source.Found | source.Skipped]:
        if not refusals:
            try:
                library(biz).scan()
            except files.LibraryError as exc:
                refusals.append(str(exc))
        yield from real(*args, **kwargs)

    monkeypatch.setattr(source, "scan_source", scan_inside)
    lib.scan()
    assert len(refusals) == 1 and "already running" in refusals[0]
    assert len(lib.find("")) == 1


