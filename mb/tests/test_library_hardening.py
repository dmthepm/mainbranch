# --- finding 5: a deep tree does not abort the scan ------------------------


def _deep(root: Path, levels: int) -> Path:
    path = root
    for _ in range(levels):
        path = path / "d"
        path.mkdir(parents=True, exist_ok=True)
    return path


@needs_nonroot
def test_a_very_deep_tree_is_skipped_with_a_reason_not_a_crash(tmp_path: Path) -> None:
    root = tmp_path / "deep"
    root.mkdir()
    leaf_dir = _deep(root, 550)
    (leaf_dir / "leaf.jpg").write_bytes(b"leaf")
    os.utime(leaf_dir / "leaf.jpg", (OLD, OLD))
    (root / "top.jpg").write_bytes(b"top")
    os.utime(root / "top.jpg", (OLD, OLD))
    lock(root)
    try:
        items = list(source.scan_source(root, {}, now_ns=OLD * 10**9 * 2))
    finally:
        unlock(root)
    found = [i.rel for i in items if isinstance(i, source.Found)]
    skipped = [i for i in items if isinstance(i, source.Skipped)]
    assert found == ["top.jpg"]
    assert [s.reason for s in skipped] == ["too-deep"]


@needs_nonroot
def test_the_library_reports_the_deep_skip_and_finishes(biz: Path, tmp_path: Path) -> None:
    root = tmp_path / "sources" / "deep"
    root.mkdir(parents=True)
    leaf_dir = _deep(root, 550)
    (leaf_dir / "leaf.jpg").write_bytes(b"leaf")
    os.utime(leaf_dir / "leaf.jpg", (OLD, OLD))
    (root / "top.jpg").write_bytes(b"top")
    os.utime(root / "top.jpg", (OLD, OLD))
    lock(root)
    try:
        lib = library(biz, init=True)
        lib.add_source("deep", root)
        report = lib.scan()
    finally:
        unlock(root)
    assert report.indexed == 1
    assert [s.reason for s in report.skipped] == ["too-deep"]


# --- finding 1: nothing the library writes can be redirected by a folder swap -


@pytest.mark.parametrize("rel", [".", ".mb", ".mb/private"])
def test_every_folder_on_the_way_in_is_checked_not_only_the_last(biz: Path, rel: str) -> None:
    library(biz, init=True)
    folder = biz / rel
    before = folder.stat().st_mode & 0o777
    folder.chmod(0o775)
    try:
        with pytest.raises(files.LibraryError, match="writable by group or others"):
            library(biz, init=True)
    finally:
        folder.chmod(before)


def test_a_folder_owned_by_someone_else_is_refused_at_every_step(
    biz: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    library(biz, init=True)
    me = os.geteuid()
    monkeypatch.setattr(os, "geteuid", lambda: me + 1)
    with pytest.raises(files.LibraryError, match="not owned"):
        files.open_dir(biz, ".mb", create=False)


@needs_nonroot
def test_a_folder_swapped_for_a_symlink_mid_scan_cannot_redirect_the_index(
    biz: Path,
    tree: Callable[[dict[str, bytes]], Path],
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    src = tree({"clip.jpg": b"first"})
    lib = library(biz, init=True)
    lib.add_source("studio", src)
    elsewhere = tmp_path / "elsewhere"
    (elsewhere / "library").mkdir(parents=True)
    real = source.scan_source
    swapped: list[bool] = []

    def swap_then_scan(*args: Any, **kwargs: Any) -> Iterator[source.Found | source.Skipped]:
        if not swapped:
            swapped.append(True)
            os.rename(biz / ".mb/private", biz / ".mb/held")
            os.symlink(elsewhere, biz / ".mb/private")
        yield from real(*args, **kwargs)

    monkeypatch.setattr(source, "scan_source", swap_then_scan)
    lib.scan()
    assert swapped
    assert list((elsewhere / "library").iterdir()) == []
    assert (biz / ".mb/held/library/index.json").is_file()


